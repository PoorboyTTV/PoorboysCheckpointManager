"""Bakes Poorboy's logo into the overlay: writes HCMInternal\\PoorboyLogoData.h (the logo is white, so only its alpha).

    python tools\\make_logo.py [<logo png>]      (default tools\\poorboy_logo.png)

  A bigger source (the 4K shirt print) is first shrunk to WIDTH wide and saved as tools\\poorboy_logo.png. The overlay
  shrinks it again to the size it draws (PoorboyLogo.cpp), so WIDTH only has to cover the largest screens.
"""
import os
import sys

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
STORED = os.path.join(HERE, 'poorboy_logo.png')
OUT = os.path.join(ROOT, 'HCMInternal', 'PoorboyLogoData.h')
WIDTH = 400


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else STORED
    im = Image.open(src).convert('RGBA')
    bbox = im.getchannel('A').getbbox()
    if bbox:
        im = im.crop(bbox)
    if im.width > WIDTH:
        im = im.resize((WIDTH, round(im.height * WIDTH / im.width)), Image.BOX)
    if os.path.abspath(src) != os.path.abspath(STORED):
        white = Image.new('RGBA', im.size, (255, 255, 255, 0))
        white.putalpha(im.getchannel('A'))
        white.save(STORED, optimize=True)
    alpha = im.getchannel('A').tobytes()
    rows = []
    for i in range(0, len(alpha), 32):
        rows.append('\t' + ','.join('0x%02X' % b for b in alpha[i:i + 32]) + ',')
    with open(OUT, 'w', newline='\n') as f:
        f.write('#pragma once\n')
        f.write('// Generated by tools\\make_logo.py from tools\\poorboy_logo.png: Poorboy\'s logo (white), its alpha row by row.\n')
        f.write('#include <cstdint>\n\n')
        f.write('constexpr int kPoorboyLogoWidth = %d;\n' % im.width)
        f.write('constexpr int kPoorboyLogoHeight = %d;\n' % im.height)
        f.write('inline constexpr uint8_t kPoorboyLogoAlpha[%d] = {\n' % len(alpha))
        f.write('\n'.join(rows))
        f.write('\n};\n')
    print('%s: %d x %d' % (OUT, im.width, im.height))


if __name__ == '__main__':
    main()
