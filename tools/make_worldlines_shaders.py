"""Compiles HCMInternal\\WorldLinesShaders.hlsl into HCMInternal\\WorldLinesShaders.h (byte arrays the map grid uses).
Run after changing the .hlsl:   python tools\\make_worldlines_shaders.py
FXC = fxc.exe (default: the newest Windows 10/11 SDK's x64 one)."""
import glob
import os
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', 'HCMInternal', 'WorldLinesShaders.hlsl')
OUT = os.path.join(HERE, '..', 'HCMInternal', 'WorldLinesShaders.h')
FXC = os.environ.get('FXC') or (sorted(glob.glob(r'C:\Program Files (x86)\Windows Kits\10\bin\10.*\x64\fxc.exe')) or [''])[-1]
ENTRIES = [('VSDepth', 'vs_5_0', 'kVSDepth'), ('VSLine', 'vs_5_0', 'kVSLine'), ('GSLine', 'gs_5_0', 'kGSLine'), ('PSLine', 'ps_5_0', 'kPSLine')]


def main():
    if not os.path.exists(FXC):
        sys.exit('fxc.exe not found (set FXC)')
    parts = ['// generated by tools\\make_worldlines_shaders.py from WorldLinesShaders.hlsl - do not edit\n#pragma once\n']
    with tempfile.TemporaryDirectory() as tmp:
        for entry, profile, name in ENTRIES:
            out = os.path.join(tmp, name + '.h')
            r = subprocess.run([FXC, '/nologo', '/O3', '/T', profile, '/E', entry, '/Vn', name, '/Fh', out, SRC], capture_output=True, text=True)
            if r.returncode:
                sys.exit(r.stdout + r.stderr)
            text = open(out).read()
            # fxc writes "const BYTE name[] =": keep only the array, with a plain type
            start = text.index('const BYTE ' + name)
            parts.append('inline ' + text[start:].replace('const BYTE', 'const unsigned char', 1).strip() + '\n')
    with open(OUT, 'w', newline='\n') as f:
        f.write('\n'.join(parts))
    print('wrote', os.path.normpath(OUT))


if __name__ == '__main__':
    main()
